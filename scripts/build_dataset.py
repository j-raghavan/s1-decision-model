"""Build the open training dataset release (Hugging Face: j-raghavan/s1-decision-data) from the training targets.

Input is the exact training file layout the fine-tune read (data/train/targets_bos100k.jsonl: 90,134 core rows with
soft targets regenerated by colab/session_relabel.py, then the 11,335 fixed rows). The release:

- stores state, question, target, teacher_calibrated and provenance as JSON text, so the rows share one schema
  (load with json.loads);
- keeps every field the trainer used (state, question, gold, target, gold_weight, holdout_family) plus the teacher's
  calibrated distribution and provenance, with each row's source licence normalised into `license`;
- drops rows whose upstream licence could not be verified (EXCLUDED_TASKS), and says how many;
- refuses to write if any row's licence is not on the provenance gate's permissive list;
- adds the custom eval sets (generated by this repo, Apache-2.0), JevBench dev/test case ids (texts stay with
  JevBench), ATTRIBUTION.md generated from lineage.yaml and the Super-NaturalInstructions manifest, and SHA256SUMS.

    uv run --no-project python scripts/build_dataset.py --targets data/train/targets_bos100k.jsonl --out hf_dataset
"""

from __future__ import annotations

import argparse
import collections
import hashlib
import importlib.util
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("check_lineage", ROOT / "scripts" / "check_lineage.py")
check_lineage = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check_lineage)

# Upstream text whose licence could not be verified: SNI marks this task MIT, but its text is English Gigaword
# newswire. The model was trained on these rows; they are not redistributed.
EXCLUDED_TASKS = {"task289_gigaword_summarization.json"}
CANON = {"apache-2.0": "Apache-2.0", "mit": "MIT", "bsd": "BSD", "cc0-1.0": "CC0-1.0", "cc-by-3.0": "CC-BY-3.0",
         "cc-by-4.0": "CC-BY-4.0", "cc-by-sa": "CC-BY-SA", "cc-by-sa-3.0": "CC-BY-SA-3.0", "cc-by-sa-4.0": "CC-BY-SA-4.0",
         "oanc": "OANC"}
# row provenance `source` -> lineage.yaml entry name, where they differ
LINEAGE_NAME = {"Super-NaturalInstructions": "Super-NaturalInstructions (199 audited decision tasks)",
                "rule generator": "structured_v1 training generator",
                "synthetic": "synthetic task families (v2 pilot, v3 scale-up)"}
JSON_FIELDS = ("state", "question", "target", "teacher_calibrated", "provenance")
FIELDS = ["row_id", "family", "task_type", "state", "question", "gold", "target", "gold_weight", "holdout_family",
          "teacher", "teacher_calibrated", "teacher_conflict"]


def licences(prov: dict) -> list[str]:
    raw = prov.get("license")
    items = raw if isinstance(raw, list) else [raw]
    out = []
    for x in items:
        key = check_lineage.norm_licence(str(x or ""))
        if key not in check_lineage.PERMISSIVE_LICENCES:
            raise SystemExit(f"row licence {x!r} is not on the permissive list")
        out.append(CANON[key])
    return out


def public_row(r: dict) -> dict:
    prov = {k: v for k, v in r["provenance"].items() if k not in ("origin", "license")}
    if prov.get("hub_id") == "allenai/natural-instructions":  # not a Hub repo; the collection lives on GitHub
        prov.pop("hub_id")
        prov["url"] = "https://github.com/allenai/natural-instructions"
    out = {k: r.get(k) for k in FIELDS}
    out["license"] = " AND ".join(licences(r["provenance"]))
    out["provenance"] = prov
    for k in JSON_FIELDS:  # free-form or option-keyed: stored as JSON text so every row has the same schema
        out[k] = json.dumps(out[k], ensure_ascii=False) if out[k] is not None else None
    return out


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def attribution(by_source: collections.Counter, by_licence: collections.Counter, excluded: int) -> str:
    lineage = check_lineage.parse_lineage(ROOT / "lineage.yaml")
    meta = {e["name"]: e for e in lineage["datasets"]}
    manifest = json.loads((ROOT / "pipeline" / "sni_manifest.json").read_text(encoding="utf-8"))
    lines = ["# Attribution", "",
             "s1-decision-data is a derived dataset: rows from the sources below were converted into typed decision "
             "questions (changes were made: reformatting into state/question/options, option shuffling at training "
             "time, and soft targets added). Each row's own licence is in its `license` field; share-alike rows "
             "(CC-BY-SA) remain under their share-alike licence.", "",
             "## Sources", "", "| Source | Rows | Organisation | Licence | Link |", "| --- | ---: | --- | --- | --- |"]
    for name, n in by_source.most_common():
        e = meta.get(LINEAGE_NAME.get(name, name))
        if e is None:
            raise SystemExit(f"source {name!r} has no lineage.yaml entry")
        link = f"https://huggingface.co/datasets/{e['hub_id']}" if e.get("hub_id") else (
            "https://github.com/allenai/natural-instructions" if name.startswith("Super-Natural") else "this repository")
        licence = "per task (below)" if name.startswith("Super-Natural") else e.get("license", "")
        lines.append(f"| {name} | {n:,} | {e.get('organisation', '')} | {licence} | {link} |")
    lines += ["", "## Rows by licence", "", "| Licence | Rows |", "| --- | ---: |"]
    lines += [f"| {lic} | {n:,} |" for lic, n in by_licence.most_common()]
    lines += ["", f"{excluded} training rows from {', '.join(sorted(EXCLUDED_TASKS))} are not redistributed: the "
              "upstream text's licence could not be verified.", "",
              "## Super-NaturalInstructions tasks", "",
              "Collection: [allenai/natural-instructions](https://github.com/allenai/natural-instructions) (Apache-2.0); "
              "each task's instance licence and upstream sources:", "",
              "| Task | Upstream sources | Instance licence |", "| --- | --- | --- |"]
    for t in manifest["tasks"]:
        if t["file"] in EXCLUDED_TASKS:
            continue
        lines.append(f"| {t['file'].removesuffix('.json')} | {', '.join(t.get('source') or [])} | {', '.join(t['license'])} |")
    lines += ["", "Synthetic task families were generated by `openai/gpt-oss-120b` (Apache-2.0) and filtered against "
              "`google/gemma-4-26B-A4B-it` (Apache-2.0); soft targets come from `google/gemma-4-26B-A4B-it`.", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--targets", type=Path, required=True)
    ap.add_argument("--eval-dir", type=Path, default=ROOT / "data" / "eval")
    ap.add_argument("--out", type=Path, default=ROOT / "hf_dataset")
    args = ap.parse_args()
    if args.out.exists():
        shutil.rmtree(args.out)
    (args.out / "data").mkdir(parents=True)

    by_source, by_licence, by_type, excluded, n = (collections.Counter(), collections.Counter(), collections.Counter(), 0, 0)
    holdout = 0
    with (args.out / "data" / "train.jsonl").open("w", encoding="utf-8") as out:
        for line in args.targets.open(encoding="utf-8"):
            r = json.loads(line)
            if r["provenance"].get("task") in EXCLUDED_TASKS:
                excluded += 1
                continue
            row = public_row(r)
            out.write(json.dumps(row, ensure_ascii=False) + "\n")
            n += 1
            by_source[r["provenance"]["source"]] += 1
            by_licence[row["license"]] += 1
            by_type[row["task_type"]] += 1
            holdout += bool(row["holdout_family"])

    copied = {}
    for src, dst in (("custom_v0.jsonl", "custom_test.jsonl"), ("custom_dev_v2.jsonl", "custom_dev.jsonl")):
        if (args.eval_dir / src).exists():
            shutil.copy(args.eval_dir / src, args.out / "data" / dst)
            copied[dst] = sum(1 for _ in (args.out / "data" / dst).open())
    for src, dst in ((args.eval_dir / "jevbench_dev.jsonl", "jevbench_dev_case_ids.txt"),
                     (ROOT / "results" / "jevbench" / "subset_case_ids.txt", "jevbench_test_case_ids.txt")):
        if src.suffix == ".txt":
            shutil.copy(src, args.out / "data" / dst)
        elif src.exists():
            ids = [json.loads(line)["case_id"] for line in src.open()]
            (args.out / "data" / dst).write_text("\n".join(ids) + "\n")
        copied[dst] = sum(1 for _ in (args.out / "data" / dst).open())

    (args.out / "ATTRIBUTION.md").write_text(attribution(by_source, by_licence, excluded), encoding="utf-8")
    shutil.copy(ROOT / "DATA_CARD.md", args.out / "README.md")  # the Hugging Face dataset card
    stats = {"train_rows": n, "excluded_rows": excluded, "holdout_family_rows": holdout, "by_task_type": dict(by_type),
             "by_source": dict(by_source.most_common()), "by_licence": dict(by_licence.most_common()), "eval": copied}
    (args.out / "stats.json").write_text(json.dumps(stats, indent=1) + "\n", encoding="utf-8")
    files = sorted(p for p in args.out.rglob("*") if p.is_file() and p.name != "SHA256SUMS")
    (args.out / "SHA256SUMS").write_text("".join(f"{sha256(p)}  {p.relative_to(args.out)}\n" for p in files))
    print(json.dumps(stats, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
